/**
 * @module mpb-dialog-gallery
 * @description A custom element for creating gallery modals
 */

export default class DialogGallery extends HTMLElement {

  connectedCallback() {

    // Generate a unique ID to be set on the modal.
    function generateUniqueId(length) {
        let result = ``;
        const characters = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789-_';

        // Loop to generate characters for the specified length
        for (let i = 0; i < length; i++) {
            const randomInd = Math.floor(Math.random() * characters.length);
            result += characters.charAt(randomInd);
        }
        return result;
    }

    const range          = document.createRange();
    const breaks         = this.getElementsByTagName(`br`);
    const imgNodeList    = this.querySelectorAll(`figure`);
    const defaultImg     = imgNodeList[0];
    const defaultSrc     = defaultImg.getAttribute(`src`);
    const defaultAlt     = defaultImg.getAttribute(`alt`);
    let   imgHtmlList    = ``;
    const imgWrapper     = document.createElement(`div`);

    imgWrapper.classList.add(`masonry`);
    range.selectNodeContents(this);
    const frag = range.extractContents()
    imgWrapper.appendChild(frag);
    this.append(imgWrapper);

    // Remove the breaks generated by the Markdown parser.
    for (let i = breaks.length - 1; i >= 0; i--) {
      breaks[i].parentNode.removeChild(breaks[i]);
    }

    // Add attribute for kbd accessibility.
    imgNodeList.forEach((imgNodeList) =>
      imgNodeList.setAttribute(`tabindex`, `0`),
    );

    // Convert the nodelist to HTML so we can append it to the modal.
    imgHtmlList = Array.prototype.reduce.call(
      imgNodeList,
      (html, node) => html + (node.outerHTML || node.nodeValue),
      '',
    );

    // Call this *after* previous so it doesn't get set on the modal thumbnails.
    imgNodeList.forEach((imgNodeList) =>
      imgNodeList.setAttribute(`aria-haspopup`, `dialog`),
    );

    // Create the dialog.
    const modal       = document.createElement(`dialog`);
    const uniqueID    = generateUniqueId(24);
    const formWrapper = document.createElement(`stack-l`);
    const form        = document.createElement(`form`);
    const details     = document.createElement(`details`);

    modal.classList.add(`gallery-modal`);
    modal.setAttribute(`closedby`, `any`);
    modal.setAttribute(`id`, `img-gallery-modal-${uniqueID}`)

    formWrapper.classList.add(`modal-wrapper`);
    formWrapper.setAttribute(`tabindex`, `0`);
    formWrapper.setAttribute(`role`, `region`);
    formWrapper.setAttribute(`aria-label`, `Gallery`);

    // `method="dialog"` captures the button click and closes the dialog.
    form.setAttribute(`method`, `dialog`);

    modal.append(formWrapper);
    formWrapper.append(form);
    formWrapper.append(details);
    form.innerHTML = `
<stack-l>
  <div class="container">
    <div class="gallery--img_main">
      <figure>
        <picture>
          <source sizes srcset>
          <source sizes srcset>
          <img class="modal-current" id="current" loading="lazy">
        </picture>
        <figcaption></figcaption>
      </figure>
    </div>
    <div class="gallery--thumbs">
    </div>
  </div>
</stack-l>
            `;
    details.innerHTML = `
<summary>KEYBOARD HINTS</summary>
<stack-l class="hint-wrapper">
  <dl>
    <stack-l>
      <dt>MacOS</dt>
      <dd><pre><ul><li>Move forward     = <kbd>&rarr;</kbd> <em>or</em> <kbd>↹ Tab</kbd></li><li>Move backward    = <kbd>&larr;</kbd> <em>or</em> <kbd>⇧ Shift</kbd> + <kbd>↹ Tab</kbd></li><li>Move down        = <kbd>⇧ Shift</kbd> + <kbd>&uarr;</kbd></li><li>Move up          = <kbd>⇧ Shift</kbd> + <kbd>&darr;</kbd></li><li>Jump to end      = <kbd><span aria-hidden>⌘</span><span class="sr-only">Command key</span></kbd> + <kbd>&rarr;</kbd></li><li>Jump to start    = <kbd><span aria-hidden>⌘</span><span class="sr-only">Command key</span></kbd> + <kbd>&larr;</kbd></li><li>Display selected = <kbd>Enter</kbd></li></ul></pre>
      </dd>
      <dt>Windows</dt>
      <dd><pre><ul><li>Move forward     = <kbd>&rarr;</kbd> <em>or</em> <kbd>↹ Tab</kbd></li><li>Move backward    = <kbd>&larr;</kbd> <em>or</em> <kbd>Shift</kbd> + <kbd>↹ Tab</kbd></li><li>Move down        = <kbd>⇧ Shift</kbd> + <kbd>&uarr;</kbd></li><li>Move up          = <kbd>⇧ Shift</kbd> + <kbd>&darr;</kbd></li><li>Jump to end      = <kbd><span aria-hidden>⊞ Windows</span><span class="sr-only">Windows key</span></kbd> + <kbd>&rarr;</kbd></li><li>Jump to start    = <kbd><span aria-hidden>⊞ Windows</span><span class="sr-only">Windows key</span></kbd> + <kbd>&larr;</kbd></li><li>Display selected = <kbd>Enter</kbd></li></ul></pre></details></stack-l></dd>
    </stack-l>
  </dl>
</stack-l>
    `
    const closeButton   = document.createElement(`button`);
    const closeText     = document.createElement(`span`);
    const iconClose     = document.createElementNS(
      `http://www.w3.org/2000/svg`,
      `svg`,
    );
    const iconClosePath = document.createElementNS(
      `http://www.w3.org/2000/svg`,
      `path`,
    );

    iconClose.setAttributeNS(
      `http://www.w3.org/2000/xmlns/`,
      `xmlns`,
      `http://www.w3.org/2000/svg`,
    );
    iconClose.setAttribute(`viewBox`, `0 0 512 512`);
    iconClose.append(iconClosePath);

    iconClosePath.setAttribute(`fill`, `var(--mpb-color-text-primary)`);
    iconClosePath.setAttribute(
      `d`,
      `M256 512a256 256 0 1 0 0-512 256 256 0 1 0 0 512zM167 167c9.4-9.4 24.6-9.4 33.9 0l55 55 55-55c9.4-9.4 24.6-9.4 33.9 0s9.4 24.6 0 33.9l-55 55 55 55c9.4 9.4 9.4 24.6 0 33.9s-24.6 9.4-33.9 0l-55-55-55 55c-9.4 9.4-24.6 9.4-33.9 0s-9.4-24.6 0-33.9l55-55-55-55c-9.4-9.4-9.4-24.6 0-33.9z`
    );

    closeButton.setAttribute(`command`, `close`);
    closeButton.setAttribute(`commandfor`, `img-gallery-modal-${uniqueID}`);

    form.prepend(closeButton);

    closeButton.append(closeText);
    closeButton.append(iconClose);
    closeButton.classList.add(`modal-close`);
    closeButton.setAttribute(`autofocus`, ``);
    closeButton.setAttribute(`type`, `submit`);
    closeText.setAttribute(`class`, `sr-only`);
    closeText.append(`Close`);

    // Add the dialog.
    this.append(modal);

    const current     = modal.querySelector(`#current`);
    const modalThumbs = modal.getElementsByClassName(`gallery--thumbs`)[0];

    current.setAttribute(`src`, defaultSrc);
    current.setAttribute(`alt`, defaultAlt);

    modalThumbs.innerHTML = imgHtmlList;

    // <dialog> variables.
    const thumbs     = modal.querySelector(`.gallery--thumbs`);
    const thumbsList = modal.querySelectorAll(`.gallery--thumbs img`);
    const summary    = details.firstElementChild;
    // Set this attribute if the image source path is relative.
    // The final gallery wins because its style rule is read last.
    let cols         = this.getAttribute(`cols`);

    cols = parseInt(cols);

    // Default columns for thumbnails is 6.\
    if (!cols) {
      cols = 6;
    };

    // Maximum cols = 12.
    if ( cols > 12) {
      cols = 12;
    };

    // Update the number of columns based on the cols attribute.
    thumbs.classList.add(`gallery--thumbs_` + cols);

    // Show the keyboard hint only if the hint attribute === TRUE.
    if (!this.hasAttribute(`hint`)) {
      details.setAttribute(`hidden`, true);
    } else {
      details.removeAttribute(`hidden`);
    }

    /**
     * Open and close the dialog, update the featured image, and handle focus.
     */

    // Listen for click on image.
    imgNodeList.forEach((imgNodeList) =>
      imgNodeList.addEventListener(`click`, (e) => {
        e.preventDefault();

        // Prevent scrolling outside the modal; see
        // https://www.joshwcomeau.com/css/has/#global-detection-6.
        // This can be removed once overscroll-behavior:contain has full support
        modal.setAttribute(`data-disable-document-scroll`, true);

        const img          = e.target;
        const figure       = img.parentNode.parentNode;
        const figClone     = figure.cloneNode(true);
        const main         = modal.getElementsByClassName(`gallery--img_main`)[0];
        const currentFig   = main.getElementsByTagName(`figure`)[0];

        figClone.removeAttribute(`tabindex`);
        figClone.removeAttribute(`aria-haspopup`);

        currentFig?.replaceWith(figClone);


        // Match the clicked image so we can update its class.
        let imgSrc = img.src;

        // Get the hostname from the image URL.
        const host = imgSrc.match(/:\/\/(www\.)?(.[^/:]+)/i)[2];

        // If the image is hosted on the dev or production server or if the
        // stripProtocol attribute is set, strip the protocol and domain from
        // the URL. Only works if the URL uses a relative path!
        if (
          host === `localhost` ||
          host === `127.0.0.1` ||
          this.hasAttribute(`rel`)
        ) {
          imgSrc = imgSrc.replace(/^.*\/\/[^/]+/, '');
        }

        // Set the featured image path.
        current.src = imgSrc;

        // Find the matching thumbnail. Resulting nodelist should contain only
        // one item.
        const matchingImg = thumbs.querySelectorAll(`[src="${imgSrc}"]`)[0];

        // Remove the `current` class from every image.
        thumbsList.forEach((thumbsList) =>
          thumbsList.classList.remove(`current`),
        );

        // Add the `current` class to the thumbnail.
        matchingImg.classList.add(`current`);

        // Open the modal.
        modal.showModal();
      }),
    );

    // Listen for the enter key click.
    imgNodeList.forEach((imgNodeList) =>
      imgNodeList.addEventListener(
        `keydown`,
        (e) => {
          const img = e.target.querySelector(`img`);
          switch (e.key) {
            case `Enter`: {
              e.preventDefault();

              modal.setAttribute(`data-disable-document-scroll`, true);
              const figure       = img.parentNode.parentNode;
              const figClone     = figure.cloneNode(true);
              const main         = modal.getElementsByClassName(`gallery--img_main`)[0];
              const currentFig   = main.getElementsByTagName(`figure`)[0];

              figClone.removeAttribute(`tabindex`);
              figClone.removeAttribute(`aria-haspopup`);

              currentFig?.replaceWith(figClone);

              let imgSrc = img.src;
              const host = imgSrc.match(/:\/\/(www\.)?(.[^/:]+)/i)[2];

              if (
                host === `localhost` ||
                host === `127.0.0.1` ||
                this.hasAttribute(`hint`)
              ) {
                imgSrc = imgSrc.replace(/^.*\/\/[^/]+/, '');
              }

              current.src = imgSrc;

              thumbsList.forEach((thumbsList) =>
                thumbsList.classList.remove(`current`),
              );

              const matchingImg = thumbs.querySelectorAll(
                `[src="${imgSrc}"]`,
              )[0];

              matchingImg.classList.add(`current`);

              modal.showModal();

              break;
            }
            default:
              return;
          }
        },
        true,
      ),
    );

    // Listen for button click
    closeButton.addEventListener(`click`, (e) => {
      // Stop preventDefault() on parent elements from propagating to the button.
      e.stopPropagation();
      // Allow scrolling outside the modal.
      modal.removeAttribute(`data-disable-document-scroll`);
      // modal.close() is not necessary; method=dialog takes care of this.
    });

    // Listen for the escape key click.
    window.addEventListener(
      `keydown`,
      (e) => {
        if (e.defaultPrevented) {
          return;
        }

        switch (e.key) {
          case `Escape`:
            // Allow scrolling outside the modal.
            modal.removeAttribute(`data-disable-document-scroll`);
            break;
          default:
            return;
        }
        // Set useCapture flag to true; see
        // https://developer.mozilla.org/en-US/docs/Web/API/EventTarget/addEventListener#usecapture
      },
      true,
    );

    // Allow scrolling when ::backdrop is clicked.
    document.addEventListener(`click`, (e) => {

      if (!modal.open) return;

      modal.removeAttribute(`data-disable-document-scroll`);

      if (e.target === document.documentElement) {
        // modal.close() is handled by `closedby` attribute on <dialog>
        // except in Safari.
        if ('closedBy' in HTMLDialogElement.prototype) {
          return;
        } else {
          modal?.close();
        }
      }
    });

    /**
     * Event listeners for *inside* the modal.
     * Navigate, select featured image, and toggle <details>.
     */

    // The event listener for the modal thumbnails.
    thumbs.addEventListener(`click`, thumbClick);

    function thumbClick(e) {
      e.preventDefault();

      const thumb        = e.target;
      const current      = this.getElementsByClassName(`current`)[0];
      const figure       = thumb.parentNode.parentNode;
      const figClone     = figure.cloneNode(true);
      const main         = modal.getElementsByClassName(`gallery--img_main`)[0];
      const currentFig   = main.getElementsByTagName(`figure`)[0];

      figClone.removeAttribute(`tabindex`);
      currentFig?.replaceWith(figClone);

      // Remove the `current` class to reset the thumbnail opacity.
      thumbsList.forEach((thumbsList) =>
        thumbsList.classList.remove(`current`),
      );

      // Add fade-in class to the featured image.
      current.classList.add(`fade-in`);

      // Remove fade-in class after .5 seconds.
      setTimeout(() => current.classList.remove(`fade-in`), 500);

      // Add the `current` class to change the opacity on the clicked image.
      thumb.classList.add(`current`);
    }

    thumbs.addEventListener(
      `keydown`,
      (e) => {
        const thumb       = e.target.querySelector(`img`);
        const prevFocused = document.activeElement;
        const parent      = prevFocused.parentNode;
        const prevIndex   = Array.prototype.indexOf.call(
          parent.children,
          prevFocused,
        );
        const total       = thumbsList.length;
        const remainder   = total % cols;
        const goUp        = total - remainder + 1 + prevIndex;
        const goUpShort   = total - remainder - (cols - 1) + prevIndex;
        const goDown      = remainder - total + (prevIndex + 1);
        let goDownShort   = remainder - total + (cols + 1) + prevIndex;

        if (goDownShort > cols) {
          goDownShort = goDownShort - cols;
        }

        if (e.defaultPrevented) {
          return; // Do nothing if the event was already processed
        }

        if (e.metaKey) {
          // The CMD key combo listener.
          switch (e.key) {
            case `ArrowLeft`: {
              e.preventDefault();

              // Get the first thumbnail.
              const firstFocused = prevFocused.parentNode.firstElementChild;

              // Move focus to the first thumbnail.
              firstFocused.focus();

              break;
            }

            case `ArrowRight`: {
              e.preventDefault();

              // Get the last thumbnail.
              const lastFocused = prevFocused.parentNode.lastElementChild;

              // Move focus to the last thumbnail.
              lastFocused.focus();

              break;
            }

            default:
              return;
          }
          // Cancel the default action to avoid it being handled twice.
          e.preventDefault();
        } else if (e.shiftKey) {
          // The shift key combo listener.
          switch (e.key) {
            case `ArrowUp`: {
              e.preventDefault();

              // Get the offset to the previous row, based on `cols` attribute.
              const upFocusedIndex = prevIndex - (cols - 1);

              let upFocused;

              // Offset is not a negative number.
              if (upFocusedIndex > 0) {
                // Find the element directly above.
                upFocused = parent.querySelector(
                  `:nth-child(${upFocusedIndex})`,
                );
              } else {
                // But if offset is negative, to to the last row.
                upFocused = parent.querySelector(`:nth-child(${goUp})`);

                // If selected image is on the penultimate row but has no image
                // below it (because the last row is short), jump to the first
                // row.
                if (upFocused < total) {
                  upFocused = parent.querySelector(`:nth-child(${goUpShort})`);
                }
              }

              // Move focus to the element.
              upFocused.focus();

              break;
            }

            case `ArrowDown`: {
              e.preventDefault();

              // Get the offset to the next row, based on `cols` attribute.
              const downFocusedIndex = prevIndex + (cols + 1);

              let downFocused;

              // Index does not exceed the number of items.
              if (downFocusedIndex < total + 1) {
                downFocused = parent.querySelector(
                  `:nth-child(${downFocusedIndex})`,
                );
              } else {
                // Index exceeds number of items; jump to first row.
                downFocused = parent.querySelector(`:nth-child(${goDown})`);

                // Item is in penultimate row and last row is short; calculate
                // offset to find first row.
                if (downFocusedIndex > total - (cols + 1)) {
                  downFocused = parent.querySelector(
                    `:nth-child(${goDownShort})`,
                  );
                }
              }

              downFocused.focus();

              break;
            }

            default:
              return;
          }
          e.preventDefault();
        } else {
          switch (e.key) {
            case `Enter`: {
              e.preventDefault();

              const figure      = thumb.parentNode.parentNode;
              const figClone    = figure.cloneNode(true);
              const main        = modal.getElementsByClassName(`gallery--img_main`)[0];
              const currentFig  = main.getElementsByTagName(`figure`)[0];

              figClone.removeAttribute(`tabindex`);
              currentFig?.replaceWith(figClone);

              thumbsList.forEach((thumbsList) =>
                thumbsList.classList.remove(`current`),
              );

              current.classList.add(`fade-in`);

              setTimeout(() => current.classList.remove(`fade-in`), 500);

              thumb.classList.add(`current`);

              break;
            }

            case `ArrowLeft`: // Navigate through the thumbnails.
              if (
                (prevFocused.nodeName === `FIGURE`) &&
                (prevFocused.parentNode.classList.contains(`gallery--thumbs`) )
              ) {
                e.preventDefault();

                const prevChoice = prevFocused.previousElementSibling;

                if (prevChoice) {
                  prevChoice.focus();
                } else {
                  prevFocused.parentNode.lastElementChild.focus();
                }
              } else {
                return;
              }

              break;

            case `ArrowRight`:
              if (
                (prevFocused.nodeName === `FIGURE`) &&
                (prevFocused.parentNode.classList.contains(`gallery--thumbs`))
              ) {
                e.preventDefault();

                const nextChoice = prevFocused.nextElementSibling;

                if (nextChoice) {
                  nextChoice.focus();
                } else {
                  prevFocused.parentNode.firstElementChild.focus();
                }
              } else {
                return;
              }

              break;
            default:
              return;
          }
          e.preventDefault();
        }
      },
      true,
    );

    // Keyboard events for the <details> & <summary> element.
    summary.addEventListener(
      `keydown`,
      (e) => {
        switch (e.key) {
          case `Enter`:
            e.preventDefault();
            details.toggleAttribute(`open`);
            break;
          case ` `:
            e.preventDefault();
            details.toggleAttribute(`open`);
            break;
          default:
            return;
        }
      },
      true,
    );
  }
}

if (`customElements` in window) {
  customElements.define(`mpb-dialog-gallery`, DialogGallery);
}
